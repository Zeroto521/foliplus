"""CONFIG contract between Python and JS, derived from ``__init__`` signatures.

A control declares its configuration surface where it belongs — in its own
``__init__`` signature. :func:`derive_schema` reflects that signature and
produces the :class:`ControlSchema` dict the two downstream surfaces are
generated from:

1. ``BaseControl._config_fields`` (Python serialization side) — derived by
   ``BaseControl.__init_subclass__`` from the schema's non-runtime-only keys,
   in signature order. No control module writes its own tuple.
2. ``foliplus/js/config-schema.ts`` (TS ``ComponentConfig`` type) — generated
   by ``script/build/emit-config-schema.mjs`` from the same dump.
3. ``test/js/config-fixture.ts`` (vitest CONFIG fixture) — generated by
   ``test/js/script/emit-config-fixture.mjs`` from the same dump.

**Type tags are TS type names.** A field's ``ts`` value is either a TS
primitive construction (``"bool"`` / ``"number"`` / ``"string"`` / ``"null"``
/ ``"any"`` / ``"union"``) or the name of a type exported from somewhere in
``foliplus/js`` (``"NumberStyle"``, ``"ControlPosition"``, ``"LayerData"`` …).
The mapping is the identity: there is no internal codename layer between the
Python tag and the TS type it renders as. :func:`verify_tags` checks every tag
that renders as a type name against :data:`IMPORTS` (the type names available
to ``config-schema.ts``), so a tag typo or a rename on one side fails the dump
instead of emitting an unimported type into the generated TS.

Special-cased (not bare type names):

* ``"Record<string, ...>"`` / ``"string[]"`` / ``"unknown[]"`` — inline TS
  constructs, not imported names.
* ``"string | ProviderConfig"`` — the SearchControl ``provider`` field is a
  union of a built-in provider id and a custom ``ProviderConfig`` dict; the tag
  renders the union inline because Python has no alias to name that union.

**Values decide the CONFIG contract.** Nothing in this module is consulted at
render time: ``BaseControl._build_config`` reads ``self._config_fields``
(derived once, at class-definition time) and never touches these tables. The
schema is what :meth:`BaseControl.__init_subclass__` reads to derive
``_config_fields``, so a signature change is a *contract change*, not a
cosmetic one — the existing Python tests snapshot the emitted JSON and fail on
drift.

Usage (build tooling):

    python foliplus/_config_schema.py --dump                                    # stdout
    python foliplus/_config_schema.py --out foliplus/.build/js/config-schema.json  # file

    # Or via python -m (requires branca/folium installed):
    python -m foliplus._config_schema --dump
"""

