# Registry keyed by Python control class name. ``BaseControl`` subclasses
# without an entry here are left untouched by the derivation: they keep
# whatever ``_config_fields`` / ``default_js`` they (or a base class)
# declared. The test suite requires every shipped control to have an entry,
# so an unregistered one never ships silently.
SCHEMAS: dict[str, ControlSchema] = {
    "FullscreenControl": _FULLSCREEN,
    "ScaleControl": _SCALE,
    "LocateControl": _LOCATE,
    "LayerControl": _LAYER,
    "MeasureControl": _MEASURE,
    "SearchControl": _SEARCH,
    "HeatmapControl": _HEATMAP,
    "ExportControl": _EXPORT,
}


def config_fields(schema: ControlSchema) -> tuple[str, ...]:
    """Fields Python emits to CONFIG for one control (non-runtime, non-dynamic keys).

    Order is declaration order. Called by BaseControl's
    ``__init_subclass__``, which assigns the result to ``_config_fields`` —
    the schema is the single source and the tuple inherits this order.
    Dynamic and runtime-only fields are intentionally excluded — dynamic
    fields are emitted via ``_extra_config`` and runtime-only fields are
    JS-set.
    """
    return tuple(k for k, f in schema.items() if not f.runtime_only and not f.dynamic)


def schema_to_json() -> str:
    """Serialize the whole schema table to JSON (deterministic, sorted).

    The dumped shape is what ``script/build/emit-config-schema.mjs`` and
    ``script/emit-config-fixture.mjs`` consume. Kept stable: adding a new
    ``FieldSpec`` attribute is a schema version bump, not a silent change.
    """
    payload = {
        "version": 1,
        "shared": _field_dict_list(SHARED),
        "runtime_only": _field_dict_list(RUNTIME_ONLY),
        "controls": {
            name: _field_dict_list(schema) for name, schema in sorted(SCHEMAS.items())
        },
    }
    return json.dumps(payload, indent=2, ensure_ascii=False, sort_keys=False) + "\n"


def _field_dict_list(schema: ControlSchema) -> dict[str, dict[str, Any]]:
    """Convert one ControlSchema to a JSON-friendly dict of field dicts.

    Drops Python-only fields (``item``, ``note``) that the generators don't
    need — ``note`` is still kept so the generated TS carries docstrings.
    """
    out: dict[str, dict[str, Any]] = {}
    for name, spec in schema.items():
        entry: dict[str, Any] = {
            "ts": spec.ts,
            "optional": spec.optional or spec.runtime_only,
            "nullable": spec.nullable,
            "runtime_only": spec.runtime_only,
            "dynamic": spec.dynamic,
        }
        if spec.values is not None:
            entry["values"] = list(spec.values)
        if spec.note:
            entry["note"] = spec.note
        if spec.default is not _UNSET:
            entry["default"] = spec.default
        out[name] = entry
    return out


def _main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="foliplus._config_schema",
        description="Dump the CONFIG schema as JSON for build tooling.",
    )
    parser.add_argument(
        "--dump",
        action="store_true",
        help="Print the schema JSON to stdout (default when --out is omitted).",
    )
    parser.add_argument(
        "--out",
        metavar="PATH",
        help="Write the schema JSON to PATH instead of stdout.",
    )
    args = parser.parse_args(argv)
    text = schema_to_json()
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(_main())
