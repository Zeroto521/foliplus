/**
 * Shared runtime for foliplus map controls.
 *
 * Bundled once into dist/foliplus-common.min.js and injected by BaseControl
 * into the shared header. Exposes:
 *   - foliplus.version - build version (`git describe`), same value as the artifact banner
 *   - foliplus.geocode / foliplus.reverseGeocode - global geocoding (bidirectional cache)
 *   - foliplus.core / foliplus.platform.<module> - shared modules, registered
 *     automatically by script/build/build.mjs (see generateSharedRegistry) so new
 *     core/platform modules need no manual wiring here.
 *   - foliplus.BaseControl - base class shared by all components.
 *   - foliplus.hint - module-level hint icon registry (per-map hint lives on map.foliplus)
 *
 * Component bundles externalize #core/* and #platform/* imports to these globals
 * (see script/build/global-namespace-plugin.mjs), so shared code is included exactly
 * once instead of being inlined into every component.
 *
 * Geocoding helpers (NOMINATIM, nominatimUrl, formatAddress) live in
 * core/geocode/nominatim.ts and are statically imported by components.
 * The stateful geocode singleton lives in core/geocode/geocoder.ts.
 */
// Generated by build.mjs: registers window.foliplus.core / .common.<module>.
// The checked-in source is a comment-only stub (a .ts file, so it typechecks);
// esbuild rewrites this import to the real generated registry inside .build/
// (see resolveSharedRegistryPlugin). Tests keep importing the stub.
import "./_shared-registry.js";
import { cacheSuggestion, geocode, reverseGeocode } from "#core/geocode/index.js";
import {
  HINT_DURATION,
  HintManager,
  ensureHint,
  registerHintIcon,
} from "#core/overlay/index.js";
import { BaseControl } from "#foliplus/BaseControl.js";
import { createLogger } from "#platform/log.js";

const log = createLogger("runtime");

// -- Global namespace bootstrap --
// Ensure the global namespace object exists.
if (!window.foliplus || typeof window.foliplus !== "object") {
  window.foliplus = {} as Foliplus;
}
const foliplus = window.foliplus;

// Bail out if the shared runtime has already been initialized (it is inlined
// once per map, but this guard keeps it idempotent across reloads/embeds).
if (!foliplus.isInitialized) {
  foliplus.isInitialized = true;
  // Inlined by esbuild `define` (script/build/build.mjs) — same `git describe`
  // as the artifact banner.
  foliplus.version = __FOLIPLUS_VERSION__;

  Object.assign(window.foliplus, {
    // Global geocoding (shared bidirectional cache + throttle).
    geocode,
    reverseGeocode,
    cacheSuggestion,
    // BaseControl base class (shared by all components).
    BaseControl,
    // Hint module (per-map HintManager factory + shared icon registry).
    hint: { ensureHint, HINT_DURATION, HintManager, registerHintIcon },
  });
} else {
  // A second shared runtime is executing on a page that already initialized
  // foliplus — a page mixing builds (e.g. two foliplus versions rendered into
  // one HTML). Initialization above is skipped on purpose (the first build
  // stays authoritative), but that also means shared modules keep the first
  // build's behaviour while component bundles keep whichever build they were
  // compiled against. Silent mixed behaviour is the bug this guard reports.
  const existing = foliplus.version;
  const incoming = __FOLIPLUS_VERSION__;
  if (existing !== incoming) {
    const error = new Error(
      `mixed foliplus builds on one page: this runtime is ${incoming}, the page already initialized ${existing}`,
    );
    log.warn(
      `${error.message} — shared modules keep ${existing}; load a single foliplus version`,
    );
    // Same hook shape as `map.foliplus.onError`; the global hook is the one
    // reachable here because the shared header runs before any map exists.
    // A broken diagnostic hook is worse than none (same rule as the event bus).
    try {
      foliplus.onError?.("runtime", error);
    } catch {
      // Ignore: the warning above is already recorded.
    }
  }
}

export { cacheSuggestion, geocode, reverseGeocode };
