import { describe, expect, it } from "vitest";
import {
  buildConfigDefaultsText,
  buildControlDefaults,
  formatValue,
} from "#script/build/config-default.mjs";
import { PrettierOptions } from "#script/build/emit-config-schema.mjs";

// buildConfigDefaultsText hands its output to prettier, which resolves the repo
// config — the same multi-second budget emit-config-schema.test.ts uses.
const SLOW = 30000;

const schema = {
  version: 1,
  shared: {},
  runtime_only: {},
  controls: {
    HeatmapControl: {
      agg: { ts: "union", values: ["count", "sum"], default: "count" },
      num_classes: { ts: "number", default: 6 },
      schemes: { ts: "array_string", default: ["Blues", "Reds"] },
      color_scheme: { ts: "string", default: "Reds" },
      field: { ts: "string", default: null, nullable: true },
    },
    MeasureControl: {
      export_format: { ts: "union", values: ["geojson", "csv"], default: "geojson" },
      // A dynamic/render-time field: no Python signature default, so the map
      // must omit it rather than emit `undefined`.
      declared_filter: { ts: "object", nullable: true },
    },
  },
};

describe("buildControlDefaults", () => {
  it("keeps only fields that carry a schema default", () => {
    expect(buildControlDefaults(schema)).toEqual({
      HeatmapControl: {
        agg: "count",
        num_classes: 6,
        schemes: ["Blues", "Reds"],
        color_scheme: "Reds",
        field: null,
      },
      MeasureControl: { export_format: "geojson" },
    });
  });
});

describe("formatValue", () => {
  it("renders JSON literals in TS source form", () => {
    expect(formatValue(null)).toBe("null");
    expect(formatValue("Reds")).toBe('"Reds"');
    expect(formatValue(6)).toBe("6");
    expect(formatValue(true)).toBe("true");
    expect(formatValue([])).toBe("[]");
    expect(formatValue(["a", "b"])).toBe('["a", "b"]');
    expect(formatValue({ min: 1 })).toBe('{ "min": 1 }');
  });

  it("throws on a value the schema should never carry", () => {
    expect(() => formatValue(undefined)).toThrow("unsupported value");
    expect(() => formatValue(() => 1)).toThrow("unsupported value");
  });
});

describe("buildConfigDefaultsText", () => {
  it(
    "emits the generated module: one typed map per control, sorted keys",
    async () => {
      const text = await buildConfigDefaultsText(schema, PrettierOptions);
      expect(text).toContain("AUTO-GENERATED by script/build/emit-config-schema.mjs");
      expect(text).toContain(
        'import type { ConfigCommon, ConfigHeatmap, ConfigMeasure } from "./config-schema.js";',
      );
      expect(text).toContain(
        "HeatmapControl: Omit<ConfigHeatmap, keyof ConfigCommon>;",
      );
      // Sorted keys, not schema order: agg < color_scheme < field < num_classes <
      // schemes, and MeasureControl after HeatmapControl.
      const heatmap = text.slice(
        text.indexOf("HeatmapControl: {"),
        text.indexOf("MeasureControl: {"),
      );
      const order = [...heatmap.matchAll(/^ {4}(\w+):/gm)].map(m => m[1]);
      expect(order).toEqual(["agg", "color_scheme", "field", "num_classes", "schemes"]);
      expect(text).not.toContain("declared_filter");
      expect(text.trimEnd().endsWith("export { DEFAULT_CONFIG };")).toBe(true);
    },
    SLOW,
  );

  it(
    "is deterministic across calls",
    async () => {
      const a = await buildConfigDefaultsText(schema, PrettierOptions);
      const b = await buildConfigDefaultsText(schema, PrettierOptions);
      expect(a).toBe(b);
    },
    SLOW,
  );
});
