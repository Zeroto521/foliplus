// test/js/script/build/registry-assert — a registry that loses a namespace or a used spec fails the build
import { describe, expect, it } from "vitest";
import {
  MANUAL_CORE,
  REQUIRED_NAMESPACES,
  importCandidates,
  registryProblems,
} from "#script/build/registry-assert.mjs";

/** A generated-registry text: the three namespace lines plus import lines. */
const registryText = (...imports: string[]): string =>
  [
    "window.foliplus = window.foliplus || {};",
    "window.foliplus.core = {};",
    "window.foliplus.platform = {};",
    "window.foliplus.ui = {};",
    ...imports,
  ].join("\n");

const USED = {
  "core/geo": ["area", "distance"],
  "core/layer/registry": ["LayerRegistry"],
  "platform/dom": ["dom"],
  ui: ["createDropdown"],
  "ui/listbox": ["createListbox"],
  "foliplus/BaseControl": ["BaseControl"],
};

const COMPLETE = registryText(
  'import { area, distance } from "#core/geo/index.js";',
  'import { LayerRegistry } from "#core/layer/index.js";',
  'import { dom } from "#platform/dom.js";',
  'import { createDropdown } from "#ui/index.js";',
  'import { createListbox } from "#ui/listbox.js";',
  'import { BaseControl } from "#foliplus/BaseControl.js";',
);

describe("registryProblems", () => {
  it("accepts a registry that covers every scanned spec", () => {
    expect(registryProblems(COMPLETE, USED)).toEqual([]);
  });

  it("names every missing namespace", () => {
    const text = [
      "window.foliplus = window.foliplus || {};",
      "window.foliplus.platform = {};",
      'import { dom } from "#platform/dom.js";',
    ].join("\n");
    const problems = registryProblems(text, { "platform/dom": ["dom"] });
    expect(problems).toEqual([
      "missing namespace window.foliplus.core",
      "missing namespace window.foliplus.ui",
    ]);
  });

  it("names a spec whose import line is missing", () => {
    const text = registryText(
      'import { area } from "#core/geo/index.js";',
      'import { dom } from "#platform/dom.js";',
    );
    const problems = registryProblems(text, USED);
    expect(problems.join("\n")).toContain("spec ui/listbox");
    expect(problems.join("\n")).toContain("#ui/listbox.js");
  });

  it("exempts the core modules registered by hand in runtime/index.ts", () => {
    expect(registryProblems(COMPLETE, { "core/hint": ["showHint"] })).toEqual([]);
    expect(MANUAL_CORE.has("core/hint")).toBe(true);
  });

  it("reports an unrecognised spec rather than silently accepting it", () => {
    expect(registryProblems(COMPLETE, { weird: ["x"] })).toEqual([
      "unrecognised spec weird (1 exports)",
    ]);
  });

  it("rejects the empty one-line stub", () => {
    const problems = registryProblems(
      "// Auto-generated by build.mjs at build time. Empty stub for tests.\n",
      { "core/geo": ["area"] },
    );
    expect(problems).toHaveLength(REQUIRED_NAMESPACES.length + 1);
  });
});

describe("importCandidates", () => {
  it("maps each spec shape to the generator's import spelling", () => {
    expect(importCandidates("core/geo")).toEqual([
      "#core/geo/index.js",
      "#core/geo.js",
    ]);
    expect(importCandidates("core/layer/registry")).toEqual([
      "#core/layer/index.js",
      "#core/layer.js",
    ]);
    expect(importCandidates("platform/dom")).toEqual([
      "#platform/dom.js",
      "#platform/dom/index.js",
    ]);
    expect(importCandidates("ui")).toEqual(["#ui/index.js"]);
    expect(importCandidates("foliplus/BaseControl")).toEqual([
      "#foliplus/BaseControl.js",
    ]);
    expect(importCandidates("weird")).toEqual([]);
  });
});
