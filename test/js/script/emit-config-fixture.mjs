#!/usr/bin/env node
/**
 * Generate test/js/config-fixture.ts from the schema dump JSON.
 *
 * Produces a `makeConfig(controlName, overrides)` factory for vitest tests:
 * `CONFIG_DEFAULTS` holds one default-value map per control (from the Python
 * schema), `makeConfig` merges the shared test baseline (name/position/
 * locale_code) with that control's defaults and the caller's overrides.
 *
 * The schema JSON is read from the path given by `--json`. There is no
 * self-dump fallback: this script is a Node tool that consumes the dump
 * pytest produces (via `python foliplus/_config_schema.py --out <path>`),
 * so the JS build and every vitest run stay Python-free.
 *
 * Usage:
 *   python foliplus/_config_schema.py --out foliplus/.build/js/config-schema.json
 *   node test/js/script/emit-config-fixture.mjs --json foliplus/.build/js/config-schema.json
 *
 * The committed `test/js/config-fixture.ts` is regenerated by hand with
 * the two commands above; pytest holds the drift gate
 * (test/python/test_config_schema.py::TestConfigFixtureParity), so
 * `npx vitest` reads the committed fixture and never spawns Python.
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { format, resolveConfig } from "prettier";
import { fileURLToPath, pathToFileURL } from "url";
import { help, parseArgs } from "../../../script/args.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..", "..", "..");

// `format()` does not load the repo config on its own, so bare defaults would
// produce a file that `format:check` (printWidth 88 + the import-sort plugin)
// rejects. Resolved once at import; empty when no config is found.
//
// The argument must be a *file* path, not a directory: resolveConfig() looks
// up from the directory *containing* the path, so a directory argument skips
// that directory -- which resolved a sibling checkout's config locally and
// nothing at all in CI, leaving format() on bare prettier defaults.
// See emit-config-schema.mjs for the incident this caused.
const PrettierOptions =
  (await resolveConfig(resolve(ROOT, "package.json"), {
    editorconfig: false,
  })) ?? {};

const SPEC = {
  json: {
    type: "string",
    desc: "Path to the schema dump JSON (required — see the header comment)",
  },
  out: {
    type: "string",
    default: resolve(ROOT, "test", "js", "config-fixture.ts"),
    desc: "Output path for the generated fixture",
  },
};

const _raw = parseArgs(process.argv.slice(2), SPEC);
if (_raw.help) {
  console.log(help(SPEC));
  process.exit(0);
}
if (_raw.errors.length) {
  console.error(_raw.errors.join("\n"));
  console.error(help(SPEC));
  process.exit(1);
}
const opts = _raw;

/** One default map per control: fields whose default is declared in schema. */
const buildControlDefaults = schema => {
  const defaults = {};
  for (const [controlName, controlSchema] of Object.entries(schema.controls)) {
    const map = {};
    for (const [name, field] of Object.entries(controlSchema)) {
      if (field.default !== undefined) map[name] = field.default;
    }
    defaults[controlName] = map;
  }
  return defaults;
};

/** Format a JS value literal for the generated code. Only JSON values ever
 *  reach here — buildControlDefaults reads them straight from the schema dump —
 *  so anything else is a caller bug. Fail loudly rather than silently emit an
 *  `undefined` or `{}` literal into the fixture. */
const formatValue = val => {
  if (val === null) return "null";
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "number" || typeof val === "boolean") return String(val);
  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";
    return `[${val.map(formatValue).join(", ")}]`;
  }
  if (typeof val === "object") {
    const entries = Object.entries(val).map(
      ([k, v]) => `${JSON.stringify(k)}: ${formatValue(v)}`,
    );
    return `{ ${entries.join(", ")} }`;
  }
  throw new Error(`formatValue: unsupported value of type ${typeof val}`);
};

// ── Core (exported for unit tests) ─────────────────────────────────────────

/** Generate the config-fixture.ts text for one parsed schema JSON object.
 *  Formatted through Prettier so the output byte-matches what format:check
 *  enforces on the committed file. */
const buildConfigFixture = async schema => {
  const controlDefaults = buildControlDefaults(schema);

  const lines = [
    "// AUTO-GENERATED by test/js/script/emit-config-fixture.mjs from foliplus/_config_schema.py.",
    "// Do not edit by hand — regenerate with:",
    "//   node test/js/script/emit-config-fixture.mjs",
    "",
    'import type { ComponentConfig } from "#foliplus/config-schema.js";',
    "",
    "/** Default CONFIG values per control, from the Python schema. */",
    "const CONFIG_DEFAULTS: Record<string, Partial<ComponentConfig>> = {",
  ];

  for (const controlName of Object.keys(controlDefaults).sort()) {
    const map = controlDefaults[controlName];
    lines.push(`  ${controlName}: {`);
    for (const name of Object.keys(map).sort()) {
      lines.push(`    ${name}: ${formatValue(map[name])},`);
    }
    lines.push("  },");
  }

  lines.push(
    "};",
    "",
    "/**",
    " * Create a test CONFIG object for one control: shared test baseline (name,",
    " * position, locale_code) + that control's schema defaults + overrides.",
    " */",
    "function makeConfig(",
    "  controlName: string,",
    "  overrides?: Partial<ComponentConfig>,",
    "): ComponentConfig {",
    "  return {",
    "    name: controlName,",
    '    position: "topleft",',
    '    locale_code: "en",',
    "    ...CONFIG_DEFAULTS[controlName],",
    "    ...overrides,",
    "  };",
    "}",
    "",
    "export { makeConfig };",
    "",
  );

  return format(lines.join("\n"), { ...PrettierOptions, parser: "typescript" });
};

// ── CLI entry ──────────────────────────────────────────────────────────────

/** Resolve the schema JSON path. `--json` is required: this script never
 *  spawns Python, so the caller has to produce the dump first and point
 *  the path at it. Failing loudly beats silently trying to run
 *  `python foliplus/_config_schema.py` from a Node tool — that path is
 *  exactly the one the build is Python-free for a reason. */
const resolveSchemaJson = o => {
  if (o.json) return resolve(o.json);
  throw new Error(
    "resolveSchemaJson: --json is required. Run " +
      "`python foliplus/_config_schema.py --out <path>` first, then " +
      "`node test/js/script/emit-config-fixture.mjs --json <path>`.",
  );
};

/** Read the schema, render the fixture, write `out`. `o` is injectable so
 *  tests can drive every branch against temp paths. */
const main = async (o = opts) => {
  const schema = JSON.parse(readFileSync(resolveSchemaJson(o), "utf-8"));
  const text = await buildConfigFixture(schema);
  writeFileSync(o.out, text, "utf-8");
};

export { PrettierOptions, buildConfigFixture, formatValue, main, resolveSchemaJson };

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  await main();
}
