"""Guard: the Python test tree must mirror the production tree.

The JS side got this rule in #1313 (test/js/script/check/test-path-mirror.test.ts):
a test file names the module it tests, and a module without a test is visible.
This module is the Python half, and it is deliberately NOT a blanket mirror.
Eighty-three of the 94 files under test/python are feature tests --
test_filter.py, test_panel.py, test_rendering.py -- and there is no production
module of that name. Forcing the rule onto them would grow the allow-list to
the point of unreadability, which is exactly how a guard quietly stops meaning
anything. So three narrow rules instead:

* M1 -- a test__<stem>.py must name a real private module, and every private
  module under foliplus/ must have a test__<stem>.py unless it is listed in
  NO_PRIVATE_TEST with a reason. The double underscore is the test_ prefix
  meeting Python private-module convention, not a typo: _x.py becomes
  test__x.py.
* M2 -- no directory under test/python may hold no tracked test_*.py anywhere
  below it. The five test/python/<Control>/ shells left behind by the 2026-11
  migration (__pycache__ only, nothing tracked) sat unmarked for months because
  nothing pointed at them.
* M3 -- a test_<Name>.py must name a real control and may not import a
  different control's class. One test file naming one module under test is the
  rule the JS side already enforces.

Every decision is a pure function over sets and dicts, so the bottom of this
file can feed a deliberately broken tree and assert the guard still turns red.
That is the teeth: without it a later relaxation to prefix matching would go
unnoticed while the real tree turns green.
"""

from __future__ import annotations

import re
import subprocess
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
PKG = ROOT / "foliplus"
TESTS = ROOT / "test" / "python"
TESTS_REL = "test/python"

#: test__<stem>.py -- the private-module test (test__layer.py).
PRIVATE_TEST = re.compile(r"^test__(?P<stem>[A-Za-z0-9_]+)\.py$")
#: test_<Name>.py -- the module-mirroring test (test_LocateControl.py).
MODULE_TEST = re.compile(r"^test_(?P<stem>[A-Z][A-Za-z0-9]*)\.py$")
#: from foliplus import A, B / from foliplus.x import A
FOLIPLUS_IMPORT = re.compile(r"^from\s+foliplus(?:\.\w+)?\s+import\b", re.MULTILINE)

#: Private module without its own test__ file, plus the reason. An entry is a
#: decision, not an omission, so each one says what covers the module instead.
NO_PRIVATE_TEST = {
    "_version": (
        "generated by vcs-versioning; the body only forwards setuptools_scm "
        "values, so testing it would test setuptools_scm, not foliplus"
    ),
    "_typing": (
        "annotation-only module: ControlPosition is a bare Literal whose "
        "__args__ is a public contract, so it has no behaviour of its own. Its "
        "semantics reach the guard through foliplus/_config_schema.py, which is "
        "reflected into the TS schema and covered by test__config_schema.py"
    ),
    "_cdn_loader": (
        "covered by test/python/test_cdn.py, which pins the dependency list it "
        "hands to the shared header"
    ),
}

#: A test__ stem that is not itself a module, mapped to the module it tests.
#: A second test file for one module is a fact about the module, not about the
#: filename -- keep that explicit rather than as a prefix guess.
SUBJECT_ALIASES = {
    "_config_schema_derive": (
        "_config_schema",
        "the reflection mechanics (derive_schema / verify_tags / resolve_tag) "
        "that per-control tests cannot reach, kept apart from the schema table",
    ),
}

#: Paths under test/python allowed to import a control other than the one they
#: are named for, with the reason each time. The teeth of the rule come from
#: this being a table, not a prefix test.
CROSS_CONTROL_ALLOWLIST: dict[str, dict[str, str]] = {
    f"{TESTS_REL}/control/SearchControl/test_SearchControl.py": {
        "LayerControl": (
            "legal cross-control integration: test_search_pin_above_data_layers "
            "asserts the pin renders above a data pane, and "
            "core/layer/PaneManager is the only creator of the "
            ".foliplus-layer-pane class -- folium.GeoJson alone produces no "
            "data pane, so the LayerControl import is the cheapest way to get "
            "one"
        ),
    },
}


def private_subjects(test_stems: set[str], module_stems: set[str]) -> list[str]:
    """M1, both directions, over two sets of _-prefixed module names.

    Both sets hold module names exactly as they appear on disk
    (_config_schema, _version ...); a test__ file is re-prefixed back to its
    module name before arriving here. An unknown stem therefore means the
    module genuinely does not exist.
    """
    problems: list[str] = []
    for stem in sorted(test_stems):
        target = SUBJECT_ALIASES.get(stem, (stem,))[0]
        if target not in module_stems:
            problems.append(
                f"test__{stem[1:]}.py names module {target}.py, which does not "
                "exist under foliplus/"
            )
    # A module may be tested by a file whose stem is not its own: test__config_schema_derive.py covers _config_schema.py.
    covered = {
        target for target, _ in SUBJECT_ALIASES.values() if target in module_stems
    }
    for stem in sorted(module_stems):
        if stem in NO_PRIVATE_TEST:
            continue
        if stem not in test_stems and stem not in covered:
            problems.append(
                f"{stem}.py has no test__{stem[1:]}.py (add one, or list it in "
                "NO_PRIVATE_TEST with a reason)"
            )
    return problems


def empty_shells(dir_counts: dict[str, int]) -> list[str]:
    """M2: directories holding no tracked test_*.py anywhere below them."""
    return [
        f"{name}/ holds no tracked test_*.py -- delete it or add a test"
        for name, count in sorted(dir_counts.items())
        if count == 0
    ]


def module_mirror_problems(
    subjects: dict[str, set[str]],
    known_controls: set[str],
    cross_allowed: dict[str, dict[str, str]] | None = None,
) -> list[str]:
    """M3: each test_<Name>.py must name a control and import only it."""
    allowed = CROSS_CONTROL_ALLOWLIST if cross_allowed is None else cross_allowed
    problems: list[str] = []
    for path, imported in sorted(subjects.items()):
        stem = MODULE_TEST.match(Path(path).name).group("stem")
        if stem not in known_controls:
            problems.append(
                f"{path} names control {stem}.py, which does not exist under foliplus/"
            )
            continue
        extras = allowed.get(path, {})
        for name in sorted(imported - {stem} - set(extras)):
            problems.append(
                f"{path} imports {name}, which is not the module it is named "
                "for (move the assertion into a test named for it, or record "
                "it in CROSS_CONTROL_ALLOWLIST with a reason)"
            )
    return problems


def imported_controls(source: str) -> set[str]:
    """Every class imported straight off the foliplus package."""
    names: set[str] = set()
    for match in FOLIPLUS_IMPORT.finditer(source):
        names |= _import_names(source[match.end() :])
    return names


def _import_names(tail: str) -> set[str]:
    """The names in one import tail, across parentheses and continuations.

    Walks to the end of the import statement: a parenthesised import keeps
    running until its bracket closes, a bare one stops at the newline. A plain
    find(")") truncates the tail at the first closing bracket and silently
    drops every name after it -- that is how a guard eye goes blind.
    """
    kept: list[str] = []
    depth = 0
    for char in tail:
        if char == "(":
            depth += 1
            continue
        if char == ")":
            if depth == 0:
                break
            depth -= 1
            continue
        if char == "\n" and depth == 0:
            break
        kept.append(char)
    text = re.sub(r"#.*", "", "".join(kept))
    names: set[str] = set()
    for raw in text.split(","):
        token = raw.strip().split(" as ")[0].strip()
        if token.isidentifier():
            names.add(token)
    return names


def _tracked() -> list[str]:
    """Every file git tracks under test/python, as repo-relative posix paths."""
    out = subprocess.run(
        ["git", "ls-files", "-z", "--", TESTS_REL],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return [path for path in out.split("\0") if path]


def _private_module_stems() -> set[str]:
    """Every _x module anywhere under foliplus/: _config_schema, _version, ..."""
    stems: set[str] = set()
    for path in sorted(PKG.rglob("*.py")):
        name = path.name
        if name == "__init__.py" or not name.startswith("_"):
            continue
        stems.add(name[:-3])
    return stems


def _private_test_stems() -> set[str]:
    """Every private module a test__<stem>.py claims to test."""
    stems: set[str] = set()
    for path in TESTS.rglob("test__*.py"):
        match = PRIVATE_TEST.match(path.name)
        if match:
            stems.add("_" + match.group("stem"))
    return stems


def _module_test_subjects() -> dict[str, set[str]]:
    """test_<Name>.py paths (repo-relative) and the controls each imports."""
    subjects: dict[str, set[str]] = {}
    for path in sorted(TESTS.rglob("test_*.py")):
        if not MODULE_TEST.match(path.name):
            continue
        rel = path.relative_to(ROOT).as_posix()
        subjects[rel] = imported_controls(path.read_text(encoding="utf-8"))
    return subjects


def _control_stems() -> set[str]:
    """Every control name: single-file module or package under control/."""
    stems: set[str] = set()
    for path in sorted((PKG / "control").glob("*.py")):
        if path.name != "__init__.py":
            stems.add(path.stem)
    for path in sorted((PKG / "control").glob("*/control.py")):
        stems.add(path.parent.name)
    return stems


def _shell_dirs() -> dict[str, int]:
    """Every on-disk dir under test/python and its tracked test count below it.

    Counts are string arithmetic on the repo-relative paths git reports, so the
    rule holds on any platform without joining native separators.
    """
    counts = Counter()
    prefix = TESTS_REL + "/"
    for path in _tracked():
        if not path.endswith(".py") or not Path(path).name.startswith("test_"):
            continue
        parts = path[len(prefix) :].split("/")[:-1]
        for depth in range(len(parts) + 1):
            counts["/".join(parts[:depth])] += 1
    dirs: dict[str, int] = {}
    for path in sorted(TESTS.rglob("*")):
        if not path.is_dir() or "__pycache__" in path.parts:
            continue
        rel = path.relative_to(TESTS).as_posix()
        dirs[rel] = counts.get(rel, 0)
    return {name: count for name, count in dirs.items() if name}


def test_m1_teeth_naming_a_missing_module() -> None:
    red = private_subjects({"_nope"}, set())
    assert red and "test__nope.py" in red[0], red


def test_m1_teeth_module_without_a_test() -> None:
    red = private_subjects(set(), {"_ghost"})
    assert red and "_ghost.py" in red[0], red


def test_m1_teeth_allowlist_keeps_the_real_tree_green() -> None:
    green = private_subjects(set(), {"_version", "_typing", "_cdn_loader"})
    assert green == [], green


def test_m1_teeth_happy_path() -> None:
    green = private_subjects({"_fill_author"}, {"_fill_author"})
    assert green == [], green


def test_m1_teeth_alias_covers_its_module() -> None:
    """An aliased stem counts as covering the module it aliases to."""
    green = private_subjects({"_config_schema_derive"}, {"_config_schema"})
    assert green == [], green


def test_m1_teeth_alias_without_its_module() -> None:
    red = private_subjects({"_config_schema_derive"}, set())
    assert red and "test__config_schema_derive.py" in red[0], red


def test_m2_teeth() -> None:
    assert empty_shells({f"{TESTS_REL}/Ghost": 0})
    assert empty_shells({f"{TESTS_REL}/infra": 5}) == []


def test_m3_teeth_missing_control() -> None:
    red = module_mirror_problems(
        {f"{TESTS_REL}/control/Nope/test_Nope.py": {"Nope"}}, {"SearchControl"}
    )
    assert red and "names control Nope.py" in red[0], red


def test_m3_teeth_cross_control() -> None:
    red = module_mirror_problems(
        {
            f"{TESTS_REL}/control/SearchControl/test_SearchControl.py": {
                "LayerControl",
                "SearchControl",
            }
        },
        {"SearchControl", "LayerControl"},
        cross_allowed={},
    )
    assert red and "imports LayerControl" in red[0], red


def test_m3_teeth_allowlist_quiet() -> None:
    green = module_mirror_problems(
        {
            f"{TESTS_REL}/control/SearchControl/test_SearchControl.py": {
                "LayerControl",
                "SearchControl",
            }
        },
        {"SearchControl", "LayerControl"},
        cross_allowed=CROSS_CONTROL_ALLOWLIST,
    )
    assert green == [], green


def test_m3_import_parser_sees_multi_name_imports() -> None:
    """The parser must not miss a multi-name import (regression on M3 eye)."""
    assert imported_controls("from foliplus import LayerControl, SearchControl") == {
        "LayerControl",
        "SearchControl",
    }
    assert imported_controls(
        "from foliplus import (\n    HeatmapControl,\n    MeasureControl as MM,\n)"
    ) == {"HeatmapControl", "MeasureControl"}
    assert imported_controls("from foliplus._validate import Bound") == {"Bound"}


def test_private_tests_name_real_modules() -> None:
    problems = private_subjects(_private_test_stems(), _private_module_stems())
    assert problems == [], "\n".join(problems)


def test_every_private_module_has_a_test() -> None:
    problems = private_subjects(_private_test_stems(), _private_module_stems())
    assert problems == [], "\n".join(problems)


def test_no_shell_directory_under_test_python() -> None:
    assert empty_shells(_shell_dirs()) == []


def test_module_named_tests_import_only_their_control() -> None:
    problems = module_mirror_problems(_module_test_subjects(), _control_stems())
    assert problems == [], "\n".join(problems)
