#!/usr/bin/env node
/**
 * Generate test/js/conf-fixture.ts from the schema dump JSON.
 *
 * Produces a `makeConf` factory that returns a `ComponentConfig` pre-populated
 * with every default value from the Python schema. Tests can call
 * `makeConf({ overrides })` to get a typed CONF object.
 *
 * Usage:
 *   node script/gen-vitest-fixture.mjs [--json <path>] [--out <path>]
 *
 * Reads <path> (default: .foliplus/conf-schema.json), writes <path>
 * (default: test/js/conf-fixture.ts).
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";
import { parseArgs } from "./args.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));

const SPEC = {
  json: {
    type: "string",
    default: resolve(__dirname, "..", ".foliplus", "conf-schema.json"),
    desc: "Path to the schema dump JSON",
  },
  out: {
    type: "string",
    default: resolve(__dirname, "..", "test", "js", "conf-fixture.ts"),
    desc: "Output path for the generated fixture",
  },
};

const _raw = parseArgs(process.argv.slice(2), SPEC);
if (_raw.help) {
  console.log(
    "Usage: node script/gen-vitest-fixture.mjs [--json <path>] [--out <path>]",
  );
  process.exit(0);
}
if (_raw.errors.length) {
  console.error(_raw.errors.join("\n"));
  process.exit(1);
}
const opts = _raw;

const schema = JSON.parse(readFileSync(resolve(opts.json), "utf-8"));

/** Collect all defaults from shared + controls + runtime_only. */
function collectDefaults() {
  const defaults = {};
  for (const [name, field] of Object.entries(schema.shared)) {
    if (field.default !== undefined) defaults[name] = field.default;
  }
  for (const [, controlSchema] of Object.entries(schema.controls)) {
    for (const [name, field] of Object.entries(controlSchema)) {
      if (field.default !== undefined) defaults[name] = field.default;
    }
  }
  for (const [name, field] of Object.entries(schema.runtime_only)) {
    if (field.default !== undefined) defaults[name] = field.default;
  }
  return defaults;
}

/** Format a JS value literal for the generated code. */
function formatValue(val) {
  if (val === null) return "null";
  if (val === undefined) return "undefined";
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "number" || typeof val === "boolean") return String(val);
  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";
    return `[${val.map(formatValue).join(", ")}]`;
  }
  if (typeof val === "object") {
    const entries = Object.entries(val).map(
      ([k, v]) => `${JSON.stringify(k)}: ${formatValue(v)}`,
    );
    return `{ ${entries.join(", ")} }`;
  }
  return JSON.stringify(val);
}

const defaults = collectDefaults();
const lines = [
  "// AUTO-GENERATED by script/gen-vitest-fixture.mjs from foliplus/_schema.py.",
  "// Do not edit by hand — regenerate with:",
  "//   python -m foliplus._schema --out .foliplus/conf-schema.json",
  "//   node script/gen-vitest-fixture.mjs",
  "",
  'import type { ComponentConfig } from "#foliplus/conf-schema.js";',
  "",
  "/**",
  " * Create a test CONF object pre-populated with every default value from",
  " * the Python schema. Pass overrides to customize specific fields.",
  " */",
  "export function makeConf(overrides?: Partial<ComponentConfig>): ComponentConfig {",
  "  return {",
];

for (const [name, value] of Object.entries(defaults)) {
  lines.push(`    ${name}: ${formatValue(value)},`);
}

lines.push("    ...overrides,", "  };", "}", "");

writeFileSync(opts.out, lines.join("\n"), "utf-8");
