#!/usr/bin/env node
/**
 * Generate test/js/conf-fixture.ts from the schema dump JSON.
 *
 * Produces a `makeConf(controlName, overrides)` factory for vitest tests:
 * `CONF_DEFAULTS` holds one default-value map per control (from the Python
 * schema), `makeConf` merges the shared test baseline (name/position/
 * locale_code) with that control's defaults and the caller's overrides.
 *
 * The schema JSON is read from `foliplus/.build/js/conf-schema.json` (written
 * by script/build.mjs step 2.4 when `gen-conf-schema` runs). When the file is
 * absent — e.g. a pure test checkout that never ran the JS build — this
 * script dumps the schema itself via Python, so it stays self-contained.
 *
 * Usage:
 *   node script/gen-conf-fixture.mjs [--json <path>] [--out <path>]
 *
 * Reads <path> (default: foliplus/.build/js/conf-schema.json, self-dumped if
 * absent), writes <path> (default: test/js/conf-fixture.ts). Run by the
 * vitest globalSetup (script/conf-fixture-setup.mjs) so the fixture is always
 * up to date with the Python schema before tests import it.
 */
import { spawnSync } from "child_process";
import { existsSync, readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { format } from "prettier";
import { fileURLToPath, pathToFileURL } from "url";
import { parseArgs } from "./args.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const SPEC = {
  json: {
    type: "string",
    desc: "Path to the schema dump JSON (default: foliplus/.build/js/conf-schema.json)",
  },
  out: {
    type: "string",
    default: resolve(ROOT, "test", "js", "conf-fixture.ts"),
    desc: "Output path for the generated fixture",
  },
};

const _raw = parseArgs(process.argv.slice(2), SPEC);
/* v8 ignore start -- CLI-only help/error handling */
if (_raw.help) {
  console.log("Usage: node script/gen-conf-fixture.mjs [--json <path>] [--out <path>]");
  process.exit(0);
}
if (_raw.errors.length) {
  console.error(_raw.errors.join("\n"));
  process.exit(1);
}
/* v8 ignore stop */
const opts = _raw;

/** One default map per control: fields whose default is declared in schema. */
const buildControlDefaults = schema => {
  const defaults = {};
  for (const [controlName, controlSchema] of Object.entries(schema.controls)) {
    const map = {};
    for (const [name, field] of Object.entries(controlSchema)) {
      if (field.default !== undefined) map[name] = field.default;
    }
    defaults[controlName] = map;
  }
  return defaults;
};

/** Format a JS value literal for the generated code. */
const formatValue = val => {
  if (val === null) return "null";
  if (val === undefined) return "undefined";
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "number" || typeof val === "boolean") return String(val);
  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";
    return `[${val.map(formatValue).join(", ")}]`;
  }
  if (typeof val === "object") {
    const entries = Object.entries(val).map(
      ([k, v]) => `${JSON.stringify(k)}: ${formatValue(v)}`,
    );
    return `{ ${entries.join(", ")} }`;
  }
  return JSON.stringify(val);
};

// ── Core (exported for unit tests) ─────────────────────────────────────────

/** Generate the conf-fixture.ts text for one parsed schema JSON object.
 *  Formatted through Prettier so the output byte-matches what format:check
 *  enforces on the committed file. */
const buildConfFixture = async schema => {
  const controlDefaults = buildControlDefaults(schema);

  const lines = [
    "// AUTO-GENERATED by script/gen-conf-fixture.mjs from foliplus/_schema.py.",
    "// Do not edit by hand — regenerate with:",
    "//   node script/gen-conf-fixture.mjs",
    "",
    'import type { ComponentConfig } from "#foliplus/conf-schema.js";',
    "",
    "/** Default CONF values per control, from the Python schema. */",
    "const CONF_DEFAULTS: Record<string, Partial<ComponentConfig>> = {",
  ];

  for (const controlName of Object.keys(controlDefaults).sort()) {
    const map = controlDefaults[controlName];
    lines.push(`  ${controlName}: {`);
    for (const name of Object.keys(map).sort()) {
      lines.push(`    ${name}: ${formatValue(map[name])},`);
    }
    lines.push("  },");
  }

  lines.push(
    "};",
    "",
    "/**",
    " * Create a test CONF object for one control: shared test baseline (name,",
    " * position, locale_code) + that control's schema defaults + overrides.",
    " */",
    "function makeConf(",
    "  controlName: string,",
    "  overrides?: Partial<ComponentConfig>,",
    "): ComponentConfig {",
    "  return {",
    "    name: controlName,",
    '    position: "topleft",',
    '    locale_code: "en",',
    "    ...CONF_DEFAULTS[controlName],",
    "    ...overrides,",
    "  };",
    "}",
    "",
    "export { makeConf };",
    "",
  );

  return format(lines.join("\n"), { parser: "typescript" });
};

export { buildConfFixture };

// ── CLI entry ──────────────────────────────────────────────────────────────

/** Resolve the schema JSON path, self-dumping via Python when absent. */
const resolveSchemaJson = () => {
  if (opts.json) return resolve(opts.json);
  const built = resolve(ROOT, "foliplus/.build/js/conf-schema.json");
  if (existsSync(built)) return built;
  const pythonExe = process.env.PYTHON ?? "python";
  const dump = spawnSync(
    pythonExe,
    ["-W", "ignore", resolve(ROOT, "foliplus/_schema.py"), "--out", built],
    { stdio: "pipe", encoding: "utf-8" },
  );
  if (dump.error) throw dump.error;
  if (dump.stderr) console.error(dump.stderr);
  if (dump.status !== 0) process.exit(dump.status);
  return built;
};

/* v8 ignore start -- CLI-only entry point, not exercised by unit tests */
if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const schema = JSON.parse(readFileSync(resolveSchemaJson(), "utf-8"));
  const text = await buildConfFixture(schema);
  writeFileSync(opts.out, text, "utf-8");
}
/* v8 ignore stop */
