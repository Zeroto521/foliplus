// script/build/config-default — the runtime default map per control, generated from the schema dump
/**
 * Shared generator for the runtime CONFIG defaults, consumed by two emitters:
 *
 *   - `script/build/emit-config-schema.mjs` writes
 *     `foliplus/js/config-default.ts` (the production module controls read).
 *   - `test/js/script/emit-config-fixture.mjs` writes the vitest fixture's
 *     `CONFIG_DEFAULTS` from the same map.
 *
 * Keeping the map derivation here is what makes the runtime fallback and the
 * test fixture one derivation instead of two copies that can drift.
 *
 * The schema dump (`python -m foliplus._config_schema`) carries every CONFIG
 * field's Python-side default; `derive.py` rejects a field without one, so the
 * map is complete for the non-dynamic fields. Dynamic fields (LayerControl's
 * `data`) have no signature default and are omitted; they are optional in the
 * generated interfaces.
 */
import { format } from "prettier";

/** One default-value map per control: only fields whose schema carries a
 *  default (the dynamic, render-time fields have none). Sorted by the emitter,
 *  not here, so the caller decides layout. */
const buildControlDefaults = schema => {
  const defaults = {};
  for (const [controlName, controlSchema] of Object.entries(schema.controls)) {
    const map = {};
    for (const [name, field] of Object.entries(controlSchema)) {
      if (field.default !== undefined) map[name] = field.default;
    }
    defaults[controlName] = map;
  }
  return defaults;
};

/** Format a JS value literal for the generated code. Only JSON values ever
 *  reach here — buildControlDefaults reads them straight from the schema dump —
 *  so anything else is a caller bug. Fail loudly rather than silently emit an
 *  `undefined` or `{}` literal into a generated file. */
const formatValue = val => {
  if (val === null) return "null";
  if (typeof val === "string") return JSON.stringify(val);
  if (typeof val === "number" || typeof val === "boolean") return String(val);
  if (Array.isArray(val)) {
    if (val.length === 0) return "[]";
    return `[${val.map(formatValue).join(", ")}]`;
  }
  if (typeof val === "object") {
    const entries = Object.entries(val).map(
      ([k, v]) => `${JSON.stringify(k)}: ${formatValue(v)}`,
    );
    return `{ ${entries.join(", ")} }`;
  }
  throw new Error(`formatValue: unsupported value of type ${typeof val}`);
};

/** `HeatmapControl` → `ConfigHeatmap`, the interface name the schema emitter
 *  declares. Kept as one helper so the defaults module and the schema module
 *  cannot disagree about the naming rule. */
const interfaceNameOf = controlName => `Config${controlName.replace("Control", "")}`;

/** Generate the `foliplus/js/config-default.ts` text for one parsed schema
 *  JSON object. Formatted through Prettier with the repo config so the output
 *  byte-matches what format:check enforces on the committed file. */
const buildConfigDefaultsText = async (schema, prettierOptions) => {
  const defaults = buildControlDefaults(schema);
  const controls = Object.keys(defaults).sort();

  const lines = [
    "// AUTO-GENERATED by script/build/emit-config-schema.mjs from the foliplus._config_schema package.",
    "// Do not edit by hand — regenerate with:",
    "//   python -m foliplus._config_schema --out foliplus/.build/js/config-schema.json",
    "//   node script/build/emit-config-schema.mjs --json foliplus/.build/js/config-schema.json",
    "",
    "// Runtime CONFIG defaults per control, derived from the Python __init__",
    "// parameter defaults through the schema dump. A control reads",
    "// `CONFIG.x ?? DEFAULT_CONFIG.<Control>.x` instead of repeating the",
    "// literal, so changing a Python default and regenerating is the only way",
    "// to change the runtime fallback. JS-only constants (colors, sizes with",
    "// no Python argument) stay in the control's const.ts. Shared CONFIG fields",
    "// (name/position/locale) are not per-control Python defaults, so each map",
    "// is Omit<ConfigX, keyof ConfigCommon>.",
    `import type { ${["ConfigCommon", ...controls.map(interfaceNameOf)].join(", ")} } from "./config-schema.js";`,
    "",
    "const DEFAULT_CONFIG: {",
  ];
  for (const controlName of controls) {
    lines.push(
      `  ${controlName}: Omit<${interfaceNameOf(controlName)}, keyof ConfigCommon>;`,
    );
  }
  lines.push("} = {");
  for (const controlName of controls) {
    lines.push(`  ${controlName}: {`);
    const map = defaults[controlName];
    for (const name of Object.keys(map).sort()) {
      lines.push(`    ${name}: ${formatValue(map[name])},`);
    }
    lines.push("  },");
  }
  lines.push("};", "", "export { DEFAULT_CONFIG };", "");

  return format(lines.join("\n"), { ...prettierOptions, parser: "typescript" });
};

export { buildConfigDefaultsText, buildControlDefaults, formatValue };
